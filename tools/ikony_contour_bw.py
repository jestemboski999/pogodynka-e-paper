"""Fit visible Contour shapes to a shared 144x120, one-bit icon field."""
from pathlib import Path
import io
import fitz
from PIL import Image,ImageOps
root=Path(__file__).resolve().parents[1]
names={'sun':'sun','sun_night':'moon','partly':'partly','partly_night':'partly_night','overcast':'cloud','rain':'rain','snow':'snow','fog':'fog','storm':'storm'}
limits={'cloud':(132,100),'fog':(124,90),'moon':(98,108),'sun':(110,110)}
sheet=Image.new('L',(144*len(names),120),255)
with (root/'PanelESPink/ikony.h').open('w',encoding='utf-8') as out:
    out.write('// Generated by tools/ikony_contour_bw.py. 144x120, 1 bit, no greys.\n#pragma once\nstatic constexpr int WEATHER_ICON_W=144, WEATHER_ICON_H=120;\n')
    for i,(symbol,name) in enumerate(names.items()):
        doc=fitz.open(root/f'tools/icons/{name}.svg')
        pdf=fitz.open('pdf',doc.convert_to_pdf());p=pdf[0]
        pix=p.get_pixmap(matrix=fitz.Matrix(448/p.rect.width,448/p.rect.width),alpha=False)
        source=Image.open(io.BytesIO(pix.tobytes('png'))).convert('L')
        bounds=ImageOps.invert(source.point(lambda p:0 if p<150 else 255)).getbbox()
        source=source.crop(bounds)
        maxw,maxh=limits.get(name,(116,108));scale=min(maxw/source.width,maxh/source.height)
        shape=source.resize((round(source.width*scale),round(source.height*scale)),Image.Resampling.LANCZOS).point(lambda p:0 if p<150 else 255)
        im=Image.new('L',(144,120),255)
        im.paste(shape,((144-shape.width)//2,(120-shape.height)//2))
        assert set(im.getdata())<={0,255}
        sheet.paste(im,(144*i,0))
        data=ImageOps.invert(im).convert('1',dither=Image.Dither.NONE).tobytes()
        assert len(data)==2160
        out.write(f'static const uint8_t icon_{symbol}[] = {{\n')
        for j in range(0,len(data),32):out.write(','.join(str(v) for v in data[j:j+32])+',\n')
        out.write('};\n')
sheet.save(root/'docs/images/ikony.png')
